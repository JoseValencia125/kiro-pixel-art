-- kiro-logo.lua — Kiro ghost logo in pixel art, traced from the official mark.
-- 40x40 cells, flat violet background, rounded body, two clean eyes,
-- small notch/tail at the bottom.

local p = app.params or {}
local out = p.out or "kiro-pixel.png"
local scale = tonumber(p.scale or "12")

local BG   = Color{ r = 0x8B, g = 0x4D, b = 0xFF }
local WHITE = Color{ r = 0xFF, g = 0xFF, b = 0xFF }
local EYE   = Color{ r = 0x0A, g = 0x0A, b = 0x0A }

--  .  = background,  #  = body,  o  = eye
local TPL = {
  "........................................",
  "........................................",
  "........................................",
  "........................................",
  "........................................",
  "........................................",
  "...................####.................",
  "................##########..............",
  "...............############.............",
  "..............##############............",
  ".............################...........",
  ".............#################..........",
  "............##################..........",
  "............###################.........",
  "............###################.........",
  "...........####################.........",
  "...........#########o####o######........",
  "...........########ooo##ooo#####........",
  "...........########ooo##ooo#####........",
  "...........########ooo##ooo#####........",
  "...........#########o####o######........",
  "...........####################.........",
  "...........####################.........",
  "...........####################.........",
  "..........#####################.........",
  "..........#####################.........",
  "..........#####################.........",
  ".........######################.........",
  ".........#####################..........",
  ".........#####################..........",
  ".........#####################..........",
  ".............################...........",
  "............#################...........",
  "............################............",
  "............###############.............",
  ".............######.######..............",
  "...............##.....##................",
  "........................................",
  "........................................",
  "........................................",
}

local W, H = 40, 40
local img = Image(W * scale, H * scale)

local function block(cx, cy, col)
  for dy = 0, scale - 1 do
    for dx = 0, scale - 1 do
      img:drawPixel(cx * scale + dx, cy * scale + dy, col)
    end
  end
end

for y = 0, H - 1 do
  local row = TPL[y + 1]
  for x = 0, W - 1 do
    local ch = row:sub(x + 1, x + 1)
    if ch == "#" then block(x, y, WHITE)
    elseif ch == "o" then block(x, y, EYE)
    else block(x, y, BG) end
  end
end

if app.isUIAvailable == false then
  img:saveAs(out)
  print("wrote " .. out .. " (" .. img.width .. "x" .. img.height .. ")")
else
  local sprite = Sprite(img.width, img.height)
  while #sprite.layers > 1 do sprite:deleteLayer(sprite.layers[#sprite.layers]) end
  app.transaction("kiro-logo", function() sprite:newCel(sprite.layers[1], 1).image = img end)
  app.sprite = sprite; app.refresh()
end
